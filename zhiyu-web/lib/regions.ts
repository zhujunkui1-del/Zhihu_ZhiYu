/**
 * 知乎 IP 属地的别名 → 地区表内的标准写法。
 *
 * 知乎返回的是「美国」「澳大利亚」这类国家名，但**省级**位置我们收在「海外」下，
 * 所以需要映射：province 记为「海外」，city 记为国家名。
 */
const OVERSEAS_ALIAS: Record<string, string> = {
  海外: "海外",
  美国: "美国",
  加拿大: "加拿大",
  英国: "英国",
  澳大利亚: "澳大利亚",
  新西兰: "新西兰",
  日本: "日本",
  韩国: "韩国",
  新加坡: "新加坡",
  德国: "德国",
  法国: "法国",
};

/**
 * 把知乎的 IP 属地规整成 (province, city)。
 *
 * 三种情况：
 *   · 属地是省级名（北京 / 浙江）→ province=它，city=null，留给用户选城市
 *   · 属地是国家名（美国 / 澳大利亚）→ province=「海外」，city=国家名
 *   · 属地是「未知」或空 → 返回 null，**不编造**
 */
export function normalizeIpLocation(ip: string | null | undefined): {
  province: string | null;
  city: string | null;
} {
  const raw = (ip ?? "").trim().replace(/^IP\s*属地/, "").trim();
  if (!raw || raw === "未知" || raw === "不显示") return { province: null, city: null };
  if (PROVINCES.includes(raw)) return { province: raw, city: null };
  if (OVERSEAS_ALIAS[raw]) return { province: "海外", city: OVERSEAS_ALIAS[raw] };
  /* 认不出来的属地：记为海外 + 原名，至少不丢信息 */
  return { province: "海外", city: raw };
}

/** 省份名列表（含「全部省份」空选项由调用方补） */
export const PROVINCES: string[] = REGIONS.map((r) => r.p);

/** 取某省的城市列表；省不存在或无城市时返回空数组 */
export function citiesOf(province: string): string[] {
  return REGIONS.find((r) => r.p === province)?.c ?? [];
}

/**
 * 地区展示文案。
 * 直辖市与港澳台省市同名时只显示一次，避免出现「北京 · 北京」。
 */
export function locText(province?: string | null, city?: string | null): string {
  const p = (province ?? "").trim();
  const c = (city ?? "").trim();
  if (p && c && c !== p) return `${p} · ${c}`;
  return c || p || "—";
}
